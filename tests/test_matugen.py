class MatugenFixture(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix="matugen-")
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name) / "home with spaces"
        self.root.mkdir()
        self.env = dict(os.environ, HOME=str(self.root), XDG_CONFIG_HOME=str(self.root / "config"),
                        XDG_STATE_HOME=str(self.root / "state"), XDG_DATA_HOME=str(self.root / "data"),
                        XDG_CACHE_HOME=str(self.root / "cache"))
        self.environment = patch.dict(os.environ, self.env)
        self.environment.start()
        self.addCleanup(self.environment.stop)
        self.config = self.root / "config/matugen/config.toml"
        self.config.parent.mkdir(parents=True)
        self.generated = self.root / "state/quickshell/user/generated"
        self.preferences = self.root / "config/qssettings/config.json"
        self.preferences.parent.mkdir()
        self.save_preferences()

    def save_preferences(self, **theming):
        self.preferences.write_text(json.dumps({"appearance": {
            "wallpaperTheming": theming, "matugenDisabled": []}}))

    def run_script(self, *args, success=True):
        result = subprocess.run(["python3", str(SCRIPT), *args], env=self.env,
                                capture_output=True, text=True, timeout=30)
        if success:
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        return result


class MatugenConfigTests(MatugenFixture):
    def test_install_preserves_app_templates_and_is_idempotent(self):
        source = '# user comment\n[config]\n[config.custom_colors]\nred = "#ff0000"\n\n[templates."my.app"]\ninput_path = "./templates/app.txt"\noutput_path = "./app.txt"\npost_hook = "echo retained"\n'
        self.config.write_text(source)
        matugen.install(self.config)
        installed = self.config.read_text()
        self.assertTrue(installed.startswith(source))
        config = matugen.load_config(self.config)
        self.assertEqual(config["config"]["custom_colors"], {"red": "#ff0000"})
        self.assertEqual(config["templates"]["my.app"]["post_hook"], "echo retained")
        for name in ("quickshell", "kitty", "ghostty", "terminal", "kcolorscheme", "gtk4"):
            self.assertTrue(Path(config["templates"][name]["input_path"]).is_file())
            self.assertTrue(str(config["templates"][name]["input_path"]).startswith(str(self.config.parent)))
        matugen.install(self.config)
        self.assertEqual(self.config.read_text(), installed)
        self.assertEqual(tomllib.loads(matugen.dump_config(config)), config)

    def test_old_generated_config_migrates_without_losing_disabled_templates(self):
        generated = "# ! AUTO-GENERATED by the shell settings app\n[config]\n"
        source = '[config]\n[templates.waybar]\ninput_path="./waybar.txt"\noutput_path="./waybar.css"\n[templates.quickshell]\ninput_path="~/.config/quickshell/end4-pC/scripts/colors/matugen/quickshell-colors.json"\noutput_path="~/.local/state/quickshell/user/generated/colors.json"\n'
        self.config.write_text(generated)
        original = self.config.with_suffix(".toml.orig")
        original.write_text(source)
        matugen.install(self.config)
        config = matugen.load_config(self.config)
        self.assertIn("waybar", config["templates"])
        self.assertEqual(original.read_text(), source)
        self.assertEqual(self.config.with_suffix(".toml.pre-matugen-only").read_text(), generated)
        self.assertEqual(config["templates"]["quickshell"]["input_path"],
                         str(self.config.parent / "templates/quickshell-colors.json"))

    def test_template_gates_include_qt_and_every_terminal(self):
        preferences = {"appearance": {"wallpaperTheming": {"enableTerminal": False, "enableQtApps": False},
                                      "matugenDisabled": ["custom", "quickshell"]}}
        for name in ("kitty", "ghostty", "terminal", "qt5ct", "qt6ct", "kcolorscheme", "custom"):
            self.assertFalse(matugen.template_enabled(name, {}, preferences, False), name)
        self.assertTrue(matugen.template_enabled("quickshell", {}, preferences, False))
        for name in ("quickshell", "kitty", "gtk4", "custom"):
            self.assertEqual(matugen.template_enabled(name, {}, preferences, True), name == "quickshell")

    def test_invalid_config_is_preserved(self):
        self.config.write_text("[config\ninvalid")
        self.run_script("--install", success=False)
        self.assertEqual(self.config.read_text(), "[config\ninvalid")

    def test_color_regeneration_does_not_touch_wallpaper_processes(self):
        preferences = json.loads(self.preferences.read_text())
        preferences["background"] = {"wallpaperPath": str(self.root / "current.png")}
        preferences["appearance"]["palette"] = {"type": "scheme-neutral", "accentColor": ""}
        self.preferences.write_text(json.dumps(preferences))
        self.generated.mkdir(parents=True)
        (self.generated / "color.txt").write_text("#78a9ff")
        commands = self.root / "commands.log"
        env = dict(self.env, COMMAND_LOG=str(commands))
        result = subprocess.run(["bash", "-c", '''
niri() { echo niri >> "$COMMAND_LOG"; }
pkill() { echo pkill >> "$COMMAND_LOG"; }
gsettings() { :; }
python3() { printf '%s\n' "$@" >> "$COMMAND_LOG"; }
export -f niri pkill gsettings python3
bash "$1" --noswitch --mode dark
''', "test", str(REPOSITORY / "scripts/colors/switchwall.sh")], env=env,
            capture_output=True, text=True, timeout=10)
        self.assertEqual(result.returncode, 0, result.stderr)
        log = commands.read_text()
        self.assertIn("--image\n" + str(self.root / "current.png"), log)
        self.assertNotIn("niri", log)
        self.assertNotIn("pkill", log)
        self.assertEqual(json.loads(self.preferences.read_text()), preferences)
        self.assertTrue((self.root / "config/gtk-3.0/settings.ini").exists())
        self.assertFalse((self.root / ".config/gtk-3.0/settings.ini").exists())

    def test_invalid_switch_arguments_fail_without_changing_preferences(self):
        before = self.preferences.read_bytes()
        for args in (("--mode",), ("--image",), ("--type",), ("--start-dir",), ("--mode", "pink")):
            with self.subTest(args=args):
                result = subprocess.run(["bash", str(REPOSITORY / "scripts/colors/switchwall.sh"), *args],
                                        env=self.env, capture_output=True, text=True, timeout=5)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(self.preferences.read_bytes(), before)

    def test_generic_name_migration_preserves_customised_templates(self):
        template_dir = self.config.parent / "templates"
        template_dir.mkdir()
        legacy = template_dir / "end4-kitty.conf"
        legacy.write_text("customised kitty template")
        (template_dir / "kitty.conf").write_text("existing generic template")
        self.config.write_text(f'[config]\n[templates.kitty]\ninput_path = "{legacy}"\noutput_path = "./kitty.conf"\n')
        matugen.install(self.config)
        config = matugen.load_config(self.config)
        migrated = Path(config["templates"]["kitty"]["input_path"])
        self.assertEqual(migrated.name, "kitty-custom.conf")
        self.assertEqual(migrated.read_text(), "customised kitty template")
        self.assertEqual((template_dir / "kitty.conf").read_text(), "existing generic template")
        self.assertFalse(legacy.exists())
        source = self.config.read_bytes()
        matugen.install(self.config)
        self.assertEqual(self.config.read_bytes(), source)

    def test_flatpak_override_is_global_read_only_and_idempotent(self):
        with patch.object(matugen.shutil, "which", return_value="/usr/bin/flatpak"), patch.object(
                matugen.subprocess, "run", return_value=SimpleNamespace(stdout="")) as run:
            matugen.ensure_flatpak_styles()
            self.assertEqual(run.call_args_list[0].args[0], ["flatpak", "override", "--user", "--show"])
            self.assertEqual(run.call_args_list[1].args[0], ["flatpak", "override", "--user",
                "--filesystem=xdg-config/gtk-3.0:ro", "--filesystem=xdg-config/gtk-4.0:ro"])
            run.reset_mock()
            run.return_value.stdout = "[Context]\nfilesystems=xdg-config/gtk-3.0:ro;xdg-config/gtk-4.0:ro;\n"
            matugen.ensure_flatpak_styles()
            self.assertEqual(run.call_count, 1)

    def test_disabled_wallpaper_theming_does_not_grant_sandbox_access(self):
        self.save_preferences(enableAppsAndShell=False)
        with patch.object(matugen.sys, "argv", [str(SCRIPT), "--install"]), patch.object(
                matugen, "ensure_flatpak_styles") as grant:
            matugen.main()
            grant.assert_not_called()


@unittest.skipUnless(shutil.which("matugen"), "Matugen is required")
class MatugenGenerationTests(MatugenFixture):
    def setUp(self):
        super().setUp()
        matugen.install(self.config)

    def test_light_shell_and_forced_dark_terminal_have_separate_outputs(self):
        self.save_preferences(terminalGenerationProps={"forceDarkMode": True})
        source = self.config.read_text()
        self.run_script("--color", "78a9ff", "--mode", "light", "--scheme", "auto")
        shell = json.loads((self.generated / "colors.json").read_text())
        terminal = json.loads((self.generated / "terminal/colors.json").read_text())
        self.assertNotEqual(shell["background"], terminal["background"])
        self.assertIn("on_surface", shell)
        self.assertNotIn("term1", shell)
        self.assertEqual(len({terminal[f"term{i}"] for i in range(1, 7)}), 6)
        kitty = (self.generated / "terminal/kitty-theme.conf").read_text()
        self.assertIn("background " + terminal["background"], kitty)
        self.assertIn("color2 " + terminal["term2"], kitty)
        qt = (self.root / "config/qt6ct/qt6ct.conf").read_text()
        self.assertIn("custom_palette=true", qt)
        self.assertIn(str(self.root / "data/color-schemes/Matugen.colors"), qt)
        self.assertIn("--accent-bg-color:", (self.root / "config/gtk-4.0/colors.css").read_text())
        self.assertEqual(self.config.read_text(), source)

    def test_lock_palette_does_not_touch_apps_live_palette_or_mode(self):
        self.run_script("--color", "#78a9ff")
        before = {path: path.read_bytes() for path in self.root.rglob("*") if path.is_file()}
        hook_log = self.root / "hook.log"
        config = matugen.load_config(self.config)
        config["templates"]["quickshell"]["post_hook"] = f"touch '{hook_log}'"
        self.config.write_text(matugen.dump_config(config))
        before[self.config] = self.config.read_bytes()
        self.run_script("--color", "#ff9944", "--mode", "light", "--lock")
        self.assertFalse(hook_log.exists())
        lock = json.loads((self.generated / "colors-lock.json").read_text())
        live = json.loads((self.generated / "colors.json").read_text())
        self.assertNotEqual(lock["primary"], live["primary"])
        for path, contents in before.items():
            if path.name != ".setup.lock":
                self.assertEqual(path.read_bytes(), contents, str(path))

    def test_disabled_app_groups_are_not_generated_or_configured(self):
        self.save_preferences(enableTerminal=False, enableQtApps=False)
        self.run_script("--color", "#78a9ff")
        self.assertTrue((self.generated / "colors.json").exists())
        self.assertFalse((self.generated / "terminal").exists())
        self.assertFalse((self.root / "config/qt6ct").exists())
        self.assertFalse((self.root / "data/color-schemes").exists())

    def test_matugen_failure_preserves_the_last_shell_palette(self):
        self.run_script("--color", "#78a9ff")
        palette = (self.generated / "colors.json").read_bytes()
        mode = (self.config.parent / "current_mode").read_bytes()
        self.run_script("--color", "#ff9944", "--scheme", "invalid", success=False)
        self.assertEqual((self.generated / "colors.json").read_bytes(), palette)
        self.assertEqual((self.config.parent / "current_mode").read_bytes(), mode)

    def test_relative_templates_and_nested_custom_colors_still_work(self):
        config = matugen.load_config(self.config)
        config["config"]["custom_colors"] = {"custom_red": "#ff0000"}
        template = self.config.parent / "templates/custom.txt"
        template.write_text("{{colors.primary.default.hex}}")
        config["templates"]["my.app"] = {"input_path": "./templates/custom.txt", "output_path": "./custom.txt"}
        self.config.write_text(matugen.dump_config(config))
        result = self.run_script("--list")
        self.assertIn({"name": "my.app"}, json.loads(result.stdout))
        self.run_script("--color", "#78a9ff")
        self.assertRegex((self.config.parent / "custom.txt").read_text(), r"^#[0-9a-f]{6}$")

    def test_existing_user_config_gets_defaults_automatically(self):
        source = '# Keep this comment\n[config]\ncontrast = 0.1\n'
        self.config.write_text(source)
        (self.config.parent / "configs/defaults.toml").unlink()
        self.run_script("--color", "#78a9ff")
        self.assertTrue((self.generated / "colors.json").exists())
        self.assertEqual(self.config.read_text(), source)
        defaults = self.config.parent / "configs/defaults.toml"
        contents = defaults.read_bytes()
        self.run_script("--color", "#ff9944")
        self.assertEqual(defaults.read_bytes(), contents)
        self.assertEqual(self.config.read_text(), source)

    def test_drop_in_configs_are_merged_and_run_without_registration(self):
        template = self.config.parent / "templates/custom.txt"
        template.write_text("{{colors.primary.default.hex}}")
        (self.config.parent / "app.toml").write_text('''
[config.custom_colors]
red = "#ff0000"
[templates.custom]
input_path = "./templates/custom.txt"
output_path = "./first.txt"
''')
        (self.config.parent / "configs/app.toml").write_text('''
[config.custom_colors]
blue = "#0000ff"
[templates.custom]
output_path = "./custom.txt"
''')
        (self.config.parent / ".render-ignored.toml").write_text("invalid [ TOML")
        (self.config.parent / "app.toml.orig").write_text("invalid [ TOML")
        config = matugen.load_config(self.config)
        self.assertEqual(config["config"]["custom_colors"], {"red": "#ff0000", "blue": "#0000ff"})
        self.assertEqual(config["templates"]["custom"]["input_path"], "./templates/custom.txt")
        entries = json.loads(self.run_script("--list").stdout)
        self.assertEqual(entries.count({"name": "custom"}), 1)
        self.run_script("--color", "#78a9ff")
        self.assertRegex((self.config.parent / "custom.txt").read_text(), r"^#[0-9a-f]{6}$")
        self.assertFalse((self.config.parent / "first.txt").exists())
        (self.config.parent / "configs/app.toml").unlink()
        self.run_script("--color", "#78a9ff")
        self.assertTrue((self.config.parent / "first.txt").exists())

    def test_invalid_drop_in_does_not_replace_live_palette(self):
        self.run_script("--color", "#78a9ff")
        palette = (self.generated / "colors.json").read_bytes()
        fragment = self.config.parent / "broken.toml"
        fragment.write_text("invalid [ TOML")
        result = self.run_script("--color", "#ff9944", success=False)
        self.assertIn(str(fragment), result.stderr)
        self.assertEqual((self.generated / "colors.json").read_bytes(), palette)


